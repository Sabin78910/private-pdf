export type Key = keyof Dict;
const dicts: Record<Lang, Dict> = { en, ne };

let current: Lang = 'en';
export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
  try {
    localStorage.setItem('pdfapp.lang', l);
  } catch {
    /* ignore */
  }
}
export function initLang() {
  let saved: string | null = null;
  try {
    saved = localStorage.getItem('pdfapp.lang');
  } catch {
    /* ignore */
  }
  setLang(saved === 'ne' || saved === 'en' ? saved : navigator.language.startsWith('ne') ? 'ne' : 'en');
}
export const lang = () => current;
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return dicts[current][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
export const allKeys = { en, ne };
